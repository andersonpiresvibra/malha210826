/**
 * Retorna o nome da cidade amigável / operacional a partir de um ICAO/IATA.
 * Prioridade:
 * 1. Base Supabase (se o registro existir e tiver nome válido preenchido).
 * 2. Catálogo ICAO_CITY_MAP integrado do sistema.
 * 3. Fallback: o próprio ICAO em maiúsculo.
 */
export const getCityName = (icao: string, destinosDB?: any[]): string => {
  if (!icao || String(icao).trim() === '' || String(icao).trim() === '--' || String(icao).trim() === '?') {
    return '--';
  }
  const target = String(icao).trim().toUpperCase();

  // 1. Tentar localizar na base do Supabase (prioridade do banco)
  if (destinosDB && Array.isArray(destinosDB) && destinosDB.length > 0) {
    const match = destinosDB.find(d => {
      if (!d) return false;
      const dIcao = String(d.icao || d.destination || '').trim().toUpperCase();
      return dIcao === target;
    });

    if (match) {
      const dbCity = String(match.city || match.cidade || match.destination_city || '').trim();
      // Apenas usa se não for vazio e não for o próprio código ICAO repetido
      if (dbCity && dbCity !== '' && dbCity.toUpperCase() !== target) {
        return dbCity.toUpperCase();
      }
    }
  }

  // 2. Tentar localizar no catálogo de referência de alta fidelidade
  if (ICAO_CITY_MAP[target]) {
    return ICAO_CITY_MAP[target];
  }

  // 3. Tentar remoção de caracteres e prefixos
  const cleanTarget = target.replace(/[^A-Z0-9]/g, '');
  if (ICAO_CITY_MAP[cleanTarget]) {
    return ICAO_CITY_MAP[cleanTarget];
  }

  return target;
};

/**
 * Retorna o código ICAO a partir de um nome de cidade ou código IATA.
 */
export const getIcaoFromCity = (cityOrIata: string): string | null => {
  if (!cityOrIata) return null;
  const target = cityOrIata.trim().toUpperCase();

  for (const [code, city] of Object.entries(ICAO_CITY_MAP)) {
    if (code.toUpperCase() === target || city.toUpperCase() === target) {
      // Se for ICAO de 4 letras começando com S ou K ou L etc
      if (code.length === 4) return code;
    }
  }
  return null;
};

